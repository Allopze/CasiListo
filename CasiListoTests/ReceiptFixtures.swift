        /// Suma de las líneas antes de sus descuentos. En Jumbo coincide con el
        /// «SUB TOTAL» impreso; el Líder imprime su «SUBTOTAL» ya neto, así que
        /// ahí este número está calculado a mano desde el desglose del papel.
        let grossTotal: Double

        var expectedNet: Double { products.map(\.total).reduce(0, +) }
        var expectedGross: Double { products.map(\.gross).reduce(0, +) }
    }

