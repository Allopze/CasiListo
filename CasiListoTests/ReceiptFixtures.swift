/// Boletas reales transcritas línea por línea, con el desglose que imprime el
/// papel. Son la referencia contra la que se mide el reconocimiento: si el
/// parser no reproduce estos productos y estos montos, la lectura está mal.
///
/// Cada fixture se valida a sí misma: la suma de los totales brutos tiene que
/// dar el SUBTOTAL impreso, y la suma de los netos el TOTAL impreso.
enum ReceiptFixtures {

    struct ExpectedProduct {
        let name: String
        /// Total de la línea ya con el descuento aplicado, que es lo que cobró la boleta.
        let total: Double
        let quantity: Int
        /// Total antes del descuento de la línea, para cuadrar contra el SUBTOTAL.
        let gross: Double

        init(_ name: String, _ total: Double, quantity: Int = 1, gross: Double? = nil) {
            self.name = name
            self.total = total
            self.quantity = quantity
            self.gross = gross ?? total
        }
    }

    struct Fixture {
        let title: String
        let store: String
        let lines: [String]
        let products: [ExpectedProduct]
        /// TOTAL impreso al pie: lo pagado, después de descuentos.
